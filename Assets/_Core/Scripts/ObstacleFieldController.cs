using System.Collections.Generic;
using UnityEngine;

public class ObstacleFieldController : MonoBehaviour
{
    [SerializeField] DestructibleObstacle destructibleObstaclePrefab;
    [SerializeField] GameObject obstacleRoot;
    [SerializeField] Vector3 bounds;

    private const float ObstacleGap = 0.06f;
    private readonly List<DestructibleObstacle> _obstacles = new List<DestructibleObstacle>();
    private readonly List<Vector3> _placedPositions = new List<Vector3>();
    private readonly List<float> _placedRadii = new List<float>();
    private Transform _player;
    private Transform _goal;
    private MeshCollider _pathCollider;

    private Bounds ObstacleBounds => new Bounds(
        obstacleRoot != null ? obstacleRoot.transform.position : transform.position,
        new Vector3(Mathf.Abs(bounds.x), Mathf.Abs(bounds.y), Mathf.Abs(bounds.z)));

    private void OnDrawGizmos()
    {
        if (obstacleRoot == null)
            return;

        Gizmos.color = Color.red;
        Gizmos.DrawWireCube(obstacleRoot.transform.position, bounds);
    }

    public bool HasBlockingObstacles
    {
        get => FindNearestBlockingObstacle() != null;
    }

    public DestructibleObstacle FindNearestBlockingObstacle()
    {
        if (_player == null || _goal == null)
            return null;

        float radius = Mathf.Max(0.01f, _player.lossyScale.x * 0.5f);
        Vector3 start = _player.position;
        Vector3 end = _goal.position;
        UpdatePathCollider(start, end, radius);

        DestructibleObstacle nearest = null;
        float nearestDistance = float.PositiveInfinity;

        foreach (DestructibleObstacle obstacle in _obstacles)
        {
            if (obstacle == null || obstacle.IsDestroyed)
                continue;

            Collider obstacleCollider = obstacle.GetComponent<Collider>();
            if (obstacleCollider == null || !Physics.ComputePenetration(
                    _pathCollider, _pathCollider.transform.position, _pathCollider.transform.rotation,
                    obstacleCollider, obstacleCollider.transform.position, obstacleCollider.transform.rotation,
                    out _, out _))
                continue;

            float distance = (obstacle.transform.position - start).sqrMagnitude;
            if (distance >= nearestDistance)
                continue;

            nearest = obstacle;
            nearestDistance = distance;
        }

        return nearest;
    }

    public void Generate(Transform player, Transform goal, int pathObstacleCount = 28)
    {
        _obstacles.Clear();
        _placedPositions.Clear();
        _placedRadii.Clear();
        _player = player;
        _goal = goal;
        CreatePathCollider();

        int routeCount = Mathf.Max(1, pathObstacleCount);
        float obstacleRadius = GetApproximateRadius(destructibleObstaclePrefab);
        Bounds generationBounds = ObstacleBounds;
        Vector3 center = generationBounds.center;
        float halfWidth = generationBounds.extents.x;
        float halfDepth = generationBounds.extents.z;
        float spawnY = goal.position.y;
        int attempts = routeCount * 500;
        while (_obstacles.Count < routeCount && attempts-- > 0)
        {
            Vector3 candidate = new Vector3(
                Random.Range(center.x - halfWidth, center.x + halfWidth),
                spawnY,
                Random.Range(center.z - halfDepth, center.z + halfDepth));
            if (!IsSeparated(candidate, obstacleRadius))
                continue;

            Register(CreateObstacle(destructibleObstaclePrefab, candidate));
        }

        // Make the first route-clear query see the colliders just generated by this run.
        Physics.SyncTransforms();
    }

    private void CreatePathCollider()
    {
        if (_pathCollider != null)
            Destroy(_pathCollider.gameObject);

        GameObject pathObject = GameObject.CreatePrimitive(PrimitiveType.Cylinder);
        pathObject.name = "Path Clearance Cylinder";
        pathObject.transform.SetParent(transform, false);
        MeshFilter pathMesh = pathObject.GetComponent<MeshFilter>();
        Renderer pathRenderer = pathObject.GetComponent<Renderer>();
        if (pathRenderer != null)
            pathRenderer.enabled = false;

        Collider primitiveCollider = pathObject.GetComponent<Collider>();
        if (primitiveCollider != null)
            Destroy(primitiveCollider);

        _pathCollider = pathObject.AddComponent<MeshCollider>();
        _pathCollider.sharedMesh = pathMesh != null ? pathMesh.sharedMesh : null;
        _pathCollider.convex = true;
        _pathCollider.isTrigger = true;
    }

    private void UpdatePathCollider(Vector3 start, Vector3 end, float radius)
    {
        if (_pathCollider == null)
            CreatePathCollider();

        Vector3 path = end - start;
        float distance = path.magnitude;
        Transform pathTransform = _pathCollider.transform;
        pathTransform.SetPositionAndRotation((start + end) * 0.5f,
            distance > 0.001f
                ? Quaternion.FromToRotation(Vector3.up, path / distance)
                : Quaternion.identity);
        pathTransform.localScale = new Vector3(radius * 2f, Mathf.Max(0.01f, distance * 0.5f), radius * 2f);
    }

    private bool IsSeparated(Vector3 position, float radius)
    {
        for (int i = 0; i < _placedPositions.Count; i++)
        {
            float minimumDistance = radius + _placedRadii[i] + ObstacleGap;
            if ((position - _placedPositions[i]).sqrMagnitude < minimumDistance * minimumDistance)
                return false;
        }
        return true;
    }

    private void Register(DestructibleObstacle obstacle)
    {
        if (obstacle == null)
            return;

        _obstacles.Add(obstacle);
        _placedPositions.Add(obstacle.transform.position);
        _placedRadii.Add(GetApproximateRadius(obstacle));
    }

    private static float GetApproximateRadius(DestructibleObstacle obstacle)
    {
        if (obstacle == null)
            return 0.3f;

        Collider obstacleCollider = obstacle.GetComponent<Collider>();
        if (obstacleCollider is SphereCollider sphereCollider)
        {
            Vector3 scale = obstacle.transform.lossyScale;
            float maxScale = Mathf.Max(Mathf.Abs(scale.x), Mathf.Abs(scale.y), Mathf.Abs(scale.z));
            return sphereCollider.radius * maxScale;
        }

        return obstacleCollider != null ? obstacleCollider.bounds.extents.magnitude : 0.3f;
    }

    private DestructibleObstacle CreateObstacle(DestructibleObstacle template, Vector3 position)
    {
        if (template != null)
        {
            GameObject clone = Instantiate(template.gameObject, position, template.transform.rotation,
                obstacleRoot != null ? obstacleRoot.transform : transform);
            clone.name = "Random Oval Obstacle";
            return clone.GetComponent<DestructibleObstacle>();
        }

        GameObject oval = GameObject.CreatePrimitive(PrimitiveType.Sphere);
        oval.name = "Random Oval Obstacle";
        oval.transform.SetPositionAndRotation(position, Quaternion.identity);
        oval.transform.SetParent(obstacleRoot != null ? obstacleRoot.transform : transform, true);
        oval.transform.localScale = new Vector3(0.25f, 0.5f, 0.25f);
        DestructibleObstacle obstacle = oval.AddComponent<DestructibleObstacle>();

        Renderer renderer = oval.GetComponent<Renderer>();
        if (renderer != null)
        {
            Material material = new Material(renderer.sharedMaterial);
            material.color = new Color(0.25f, 0.65f, 0.25f);
            renderer.material = material;
        }

        return obstacle;
    }
}
